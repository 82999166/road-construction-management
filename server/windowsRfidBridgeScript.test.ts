import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

describe("Windows uTrust 正式写卡桥接脚本", () => {
  it("必须使用服务端下发的规范 JSON 原文，避免 PowerShell 重序列化导致回读摘要误判", () => {
    const source = readFileSync(new URL("../desktop-bridge/utrust_local_bridge.ps1", import.meta.url), "utf8");
    expect(source).toContain("claim.payloadJson");
    expect(source).toContain("$payloadJson = [string]$claim.payloadJson");
    expect(source).toContain("UTF8.GetBytes($payloadJson)");
    expect(source).toContain("claim.payloadUtf8ByteLength");
    expect(source).toContain("writeResult.payloadUtf8ByteLength");
    expect(source).toContain("expectedPayloadFingerprintPrefix");
    expect(source).toContain("actualPayloadFingerprintPrefix");
    expect(source).not.toContain("UTF8.GetBytes(($claim.payload | ConvertTo-Json");
  });

  it("正式写卡仍须执行 UID 校验、NDEF 回读、摘要比对和服务端确认，且不改变写保护设置", () => {
    const source = readFileSync(new URL("../desktop-bridge/utrust_local_bridge.ps1", import.meta.url), "utf8");
    expect(source).toContain('Invoke-RfidServer "/api/local-rfid-bridge/claim"');
    expect(source).toContain('Invoke-ReaderScript "run_utrust_rfid_write.ps1"');
    expect(source).toContain("vehicle_card_readback_fingerprint_mismatch");
    expect(source).toContain('Invoke-RfidServer "/api/local-rfid-bridge/complete"');
    expect(source).toContain('$env:RC_RFID_ALLOW_OVERWRITE = "true"');
    expect(source).toContain("function Get-FormalWriteFailureCode");
    expect(source).toContain("card_user_area_read_failed");
    expect(source).toContain("vehicle_card_readback_fingerprint_mismatch");
    expect(source).toContain('$text = if ($null -eq $Reason) { "" } else { [string]$Reason }');
    expect(source).not.toContain("$Reason ??");
    expect(source).toContain("card_write_stage_prepare");
    expect(source).toContain("card_write_prepare_failed");
    expect(source).toContain("card_writer_load_failed");
    expect(source).toContain("card_write_stage_read_user_area");
    expect(source).toContain("card_write_stage_verify_ndef");
    expect(source).toContain("server_vehicle_card_confirm_retryable");
    expect(source).toContain('if ($safeReason -ne "server_vehicle_card_confirm_retryable")');
    expect(source).toContain("failureRecorded = [bool]$failed.success");
    expect(source).toContain("server_bridge_failure_record_failed");
    expect(source).toContain("rfid_confirm_receipt.dpapi");
    expect(source).toContain("DataProtectionScope]::CurrentUser");
    expect(source).toContain('"/api/confirm-vehicle-card"');
    expect(source).toContain("Invoke-PendingVehicleConfirmation");
    expect(source).toContain('"server_vehicle_card_claim_failed"');
    expect(source).toContain('"server_vehicle_card_claim_request_invalid"');
    expect(source).toContain('"server_vehicle_card_claim_token_invalid"');
    expect(source).toContain('"server_vehicle_card_claim_uid_invalid"');
    expect(source).toContain('"application/json; charset=utf-8"');
    expect(source).toContain("Invoke-WebRequest -UseBasicParsing");
    expect(source).toContain("$_.ErrorDetails");
    expect(source).toContain("[switch]$AllowStructuredFailure");
    expect(source).toContain("[switch]$RequireSuccessProperty");
    expect(source).toContain('Invoke-ReaderScript "run_utrust_rfid_write.ps1" -AllowStructuredFailure -RequireSuccessProperty');
    expect(source).toContain('$bridgeVersion = "utrust-bridge-installer-v13"');
    expect(source).toContain('$bridgeBuildId = "utrust-rfid-installer-20261101-progress-v13"');
    expect(source).toContain('$bridgeContentSha256 = (Get-FileHash -LiteralPath $PSCommandPath -Algorithm SHA256).Hash.ToLowerInvariant()');
    expect(source).toContain('$requiredWriterVersion = "ntag216-atomic-v2"');
    expect(source).toContain('$path -eq "/ready"');
    expect(source).toContain('if ([string]$writeResult.writerVersion -ne $requiredWriterVersion)');
    expect(source).toContain('bridgeVersion = $bridgeVersion');
    expect(source).toContain('bridgeBuildId = $bridgeBuildId');
    expect(source).toContain('bridgeContentSha256 = $bridgeContentSha256');
    expect(source).toContain("function Get-StructuredReaderResult");
    expect(source).toContain('$start = $line.IndexOf("{")');
    expect(source).toContain('$end = $line.LastIndexOf("}")');
    expect(source).toContain('if ($AllowStructuredFailure -and $null -ne $structuredResult -and -not [bool]$structuredResult.success)');
    expect(source).toContain('throw "reader_script_no_structured_result"');
    expect(source).toContain('$lines = @($Text -split "`r?`n")');
    expect(source).toContain('"card_writer_no_diagnostic_result"');
    expect(source).toContain('"server_vehicle_card_claim_card_or_payload_conflict"');
    expect(source).toContain('"server_vehicle_card_claim_authorization_or_server_unavailable"');
    expect(source).not.toContain('match "写卡授权无效');
    expect(source).toContain('"claim"');
    expect(source).toContain('"complete"');
    expect(source).toContain('"/api/read-vehicle-entry"');
    expect(source).toContain("run_utrust_read_vehicle_entry.ps1");
    expect(source).toContain("vehicle_card_ndef_entry_not_allowed");
    expect(source).toContain("function Get-FormalWriteStageFailureCode");
    expect(source).toContain('$script:formalWriteStage = "read_uid"');
    expect(source).toContain('$script:formalWriteStage = "claim"');
    expect(source).toContain('$script:formalWriteStage = "invoke_writer"');
    expect(source).toContain('$script:formalWriteStage = "validate_writer_result"');
    expect(source).toContain('"/api/last-write-failure"');
    expect(source).toContain("lastFormalWriteFailure");
    expect(source).toContain('if ([string]$writeResult.payloadFingerprint -notmatch "^[a-f0-9]{64}$"');
    expect(source).toContain('throw "card_writer_result_invalid"');
    expect(source).toContain("function New-PayloadFingerprintMismatchException");
    expect(source).toContain('New-Object -TypeName System.InvalidOperationException -ArgumentList @(\"vehicle_card_readback_fingerprint_mismatch\")');
    expect(source).toContain('$exception.Data["rfidSafeDiagnostics"] = $diagnostics');
    expect(source).toContain("function Get-FormalWriteExceptionDiagnostics");
    expect(source).toContain('$failureDiagnostics = Get-FormalWriteExceptionDiagnostics $_.Exception');
    expect(source).toContain("diagnostics = $failureDiagnostics");
    expect(source).toContain("function Invoke-VerifiedVehicleConfirmation");
    expect(source).toContain('"/api/verify-and-confirm-vehicle-card"');
    expect(source).toContain('$env:RC_RFID_VERIFY_ONLY = "true"');
    expect(source).toContain('wroteCard = $false');
    expect(source).toContain('confirmationMode = "verify_existing_ndef"');
    expect(source).toContain('readbackVerified = $true');
    const completeStageIndex = source.indexOf('$script:formalWriteStage = "complete"');
    const receiptStageIndex = source.indexOf('$script:formalWriteStage = "save_pending_confirmation"');
    expect(completeStageIndex).toBeGreaterThan(-1);
    expect(receiptStageIndex).toBeGreaterThan(completeStageIndex);
  });

  it("C# 写卡器必须按 CC 声明容量限制用户区读写，并保留实际 NDEF 字节回读校验", () => {
    const source = readFileSync(new URL("../desktop-bridge/UTrustNtag216RfidWrite.cs", import.meta.url), "utf8");
    expect(source).toContain("int ndefCapacityBytes = cc[2] * 8");
    expect(source).toContain("int userPageCount = (ndefCapacityBytes + 3) / 4");
    expect(source).toContain("ndef_exceeds_declared_card_capacity");
    expect(source).toContain("if (!ndef.SequenceEqual(verified.ToArray()))");
    expect(source).toContain('WriterVersion = "ntag216-atomic-v2"');
    expect(source).toContain('"payloadUtf8ByteLength\\":" + payloadUtf8Bytes.Length');
    expect(source).toContain('stage = "invalidate_ndef"');
    expect(source).toContain('stage = "write_ndef_body"');
    expect(source).toContain('stage = "verify_ndef_body"');
    expect(source).toContain('stage = "commit_ndef_length"');
    expect(source).toContain('WritePage(card, ref request, FirstUserPage, new byte[] { 0x00, 0x00, 0x00, 0x00 })');
    expect(source).toContain('for (int index = 1; index < pageCount; index++)');
    expect(source).toContain('WritePage(card, ref request, FirstUserPage, GetPage(ndef, 0))');
    expect(source).toContain('"committed\\":true');
    expect(source).toContain('RC_RFID_VERIFY_ONLY');
    expect(source).toContain('stage = "verify_existing_ndef"');
    expect(source).toContain('!ndef.SequenceEqual(existingBytes.Take(ndef.Length))');
    expect(source).toContain('"written\\":false,\\"verified\\":true,\\"committed\\":true,\\"verifyOnly\\":true');
    const verifyOnlyIndex = source.indexOf("if (verifyOnly)");
    const firstWriteAttemptIndex = source.indexOf("writeAttempted = true");
    expect(verifyOnlyIndex).toBeGreaterThan(-1);
    expect(firstWriteAttemptIndex).toBeGreaterThan(verifyOnlyIndex);
    expect(source).not.toContain('for (int index = 0; index < userPageCount; index++) WritePage');
    expect(source).toContain('string stage = "prepare"');
    expect(source).toContain('stage = "read_user_area"');
    expect(source).toContain('stage = "verify_ndef"');
    expect(source).toContain('"stage\\":\\"" + JsonEscape(stage)');
    expect(source).not.toContain("UserPageCount = 222");
  });

  it("正式写卡 PowerShell 包装器必须保留 C# 的结构化控制台输出并传递 Main 返回码", () => {
    const source = readFileSync(new URL("../desktop-bridge/run_utrust_rfid_write.ps1", import.meta.url), "utf8");
    expect(source).toContain('Join-Path $PSScriptRoot "UTrustNtag216RfidWrite.cs"');
    expect(source).toContain("[int][UTrustNtag216RfidWrite]::Main()");
    expect(source).toContain("exit $exitCode");
    expect(source).toContain('$wrapperVersion = "utrust-writer-wrapper-diagnostic-v3"');
    expect(source).toContain('"writer_load_failed"');
    expect(source).toContain("ConvertTo-Json -Compress");
    expect(source).not.toContain("[void][UTrustNtag216RfidWrite]::Main()");
  });

  it("只读车辆卡诊断必须报告 TLV 边界和锁定配置摘要且绝不发送写入指令", () => {
    const source = readFileSync(new URL("../desktop-bridge/UTrustVehicleCardDiagnostic.cs", import.meta.url), "utf8");
    expect(source).toContain("InspectTlv");
    expect(source).toContain('TryReadPage(card, ref request, 0xE2');
    expect(source).toContain('TryReadPage(card, ref request, 0xE3');
    expect(source).toContain('TryReadPage(card, ref request, 0xE4');
    expect(source).toContain('staticPage.Skip(2).Take(2)');
    expect(source).toContain('dynamicLockPage.Take(3)');
    expect(source).toContain('config0Page[3]');
    expect(source).toContain('(config1Page[0] & 0x80)');
    expect(source).toContain('"tlvDeclaredLength\\":"');
    expect(source).toContain('"firstAllZeroUserPage\\":"');
    expect(source).toContain('"writeOperation\\":false');
    expect(source).not.toContain("0xD6");
    expect(source).not.toContain("WritePage(");
  });

  it("Windows 唯一构建升级器必须在停止旧桥接前解析升级器和新桥接、校验首次安装所需核心文件、备份旧版、验证轻量就绪构建标识并在失败时回滚", () => {
    const upgradeUrl = new URL("../desktop-bridge/upgrade_utrust_bridge.ps1", import.meta.url);
    const source = readFileSync(upgradeUrl, "utf8");
    const upgradeBytes = readFileSync(upgradeUrl);
    const bridgeBytes = readFileSync(new URL("../desktop-bridge/utrust_local_bridge.ps1", import.meta.url));
    const wrapperBytes = readFileSync(new URL("../desktop-bridge/run_utrust_rfid_write.ps1", import.meta.url));
    for (const bytes of [upgradeBytes, bridgeBytes, wrapperBytes]) {
      expect(Array.from(bytes.subarray(0, 3))).toEqual([0xef, 0xbb, 0xbf]);
    }
    expect(source).toContain('$installerVersion = "utrust-upgrader-installer-v13"');
    expect(source).toContain('$bridgeVersion = "utrust-bridge-installer-v13"');
    expect(source).toContain('$bridgeBuildId = "utrust-rfid-installer-20261101-progress-v13"');
    expect(source).toContain('$bridgeContentSha256 = "5577dab91bdde22ca7bd230ef44cdb150637470fb5885a2ea24a127b445d3e5e"');
    expect(source).toContain('$writerVersion = "ntag216-atomic-v2"');
    expect(source).toContain("Get-FileHash -LiteralPath $sourcePath -Algorithm SHA256");
    expect(source).toContain("function Test-PowerShellScriptSyntax");
    expect(source).toContain("[System.Management.Automation.Language.Parser]::ParseFile");
    expect(source).toContain('$stage = "verify_upgrade_script_syntax"');
    expect(source).toContain('$stage = "verify_bridge_script_syntax"');
    expect(source).toContain("backup-installer-v13-");
    expect(source).toContain("Test-UTrustBridgeReady");
    expect(source).toContain('Uri "http://127.0.0.1:47601/ready"');
    expect(source).toContain("Write-UpgradeProgress");
    expect(source).toContain("return");
    expect(source).not.toContain("exit 0");
    expect(source).toContain('[string]$ready.bridgeBuildId -eq $bridgeBuildId');
    expect(source).toContain('[string]$ready.bridgeContentSha256 -eq $bridgeContentSha256');
    expect(source).toContain('Reason = "bridge_build_identity_mismatch"');
    expect(source).toContain("previousVersionRestored = $rollbackHealthy");
    for (const requiredFile of ["UTrustBridgeSupport.cs", "run_utrust_read_uid.ps1", "utrust_probe.ps1", "UTrustReadVehicleEntry.cs", "run_utrust_read_vehicle_entry.ps1"]) {
      expect(source).toContain(`"${requiredFile}" = `);
    }
  });

  it("首次安装脚本必须仅保存非敏感本机配置、检查 Windows 环境并注册当前用户登录自启动", () => {
    const installer = readFileSync(new URL("../desktop-bridge/install-utrust-bridge.ps1", import.meta.url), "utf8");
    const doubleClickLauncher = readFileSync(new URL("../desktop-bridge/安装写卡桥接.cmd", import.meta.url), "utf8");
    const doubleClickLauncherBytes = readFileSync(new URL("../desktop-bridge/安装写卡桥接.cmd", import.meta.url));
    const elevationLauncher = readFileSync(new URL("../desktop-bridge/elevate-utrust-installer.ps1", import.meta.url), "utf8");
    const packer = readFileSync(new URL("../scripts/package-utrust-first-install.mjs", import.meta.url), "utf8");
    expect(installer).toContain('$PSVersionTable.PSVersion.Major -lt 5');
    expect(installer).toContain('System32\\winscard.dll');
    expect(installer).toContain("administrator_permission_required");
    expect(installer).toContain("Register-ScheduledTask");
    expect(installer).toContain("YUEXIN_RFID_BRIDGE_ROOT");
    expect(installer).toContain("server_issued_short_lived_not_persisted");
    expect(installer).toContain("tokenPersisted = $false");
    expect(installer).not.toContain("bridgeToken =");
    expect(doubleClickLauncher).toContain("install-utrust-bridge.ps1");
    expect(doubleClickLauncher).toContain("elevate-utrust-installer.ps1");
    expect(doubleClickLauncher).toContain("-File \"%LAUNCHER%\"");
    expect(doubleClickLauncher).toContain('%SystemRoot%\\System32\\WindowsPowerShell\\v1.0\\powershell.exe');
    expect(doubleClickLauncher).not.toContain("$args[0]");
    expect(doubleClickLauncher).not.toContain("powershell.exe -NoProfile");
    expect([...doubleClickLauncherBytes].every(byte => byte === 9 || byte === 10 || byte === 13 || (byte >= 32 && byte <= 126))).toBe(true);
    expect(doubleClickLauncherBytes.includes(Buffer.from("\r\n"))).toBe(true);
    expect(doubleClickLauncherBytes.includes(Buffer.from("\n"))).toBe(true);
    expect(doubleClickLauncherBytes.toString("ascii").includes("\n") && !doubleClickLauncherBytes.toString("ascii").includes("\r\n")).toBe(false);
    expect(elevationLauncher).toContain("Join-Path $PSScriptRoot \"install-utrust-bridge.ps1\"");
    expect(elevationLauncher).toContain("-Verb RunAs");
    expect(elevationLauncher).toContain("$quotedScriptPath");
    expect(doubleClickLauncher).toContain("-ExecutionPolicy Bypass");
    expect(doubleClickLauncher).not.toContain("bridgeToken");
    for (const requiredFile of ["安装写卡桥接.cmd", "elevate-utrust-installer.ps1", "install-utrust-bridge.ps1", "UTrustBridgeSupport.cs", "run_utrust_read_uid.ps1", "utrust_probe.ps1"]) {
      expect(packer).toContain(`"${requiredFile}"`);
    }
    expect(installer).toContain('$installerVersion = "utrust-first-install-v16"');
    expect(installer).toContain("Write-InstallProgress");
    expect(installer).toContain('Uri "http://127.0.0.1:47601/ready"');
    expect(installer).toContain("bridge_upgrade_result_missing");
    expect(packer).toContain("utrust-first-install-v16");
    expect(packer).toContain("utf8Bom");
    expect(packer).toContain("Windows CMD 启动器只能包含 ASCII 字符");
    expect(packer).toContain('text.replace(/\\r?\\n/g, "\\r\\n")');
    expect(packer).toContain('import { fileURLToPath } from "node:url"');
    expect(packer).toContain("dirname(fileURLToPath(import.meta.url))");
    expect(packer).not.toContain("dirname(new URL(import.meta.url).pathname)");
    expect(packer).toContain('sourceName === "安装写卡桥接.cmd" ? "Install-Yuexin-RFID-Bridge.cmd"');
    expect(packer).toContain('const readmeFileName = "README-First-Install.txt"');
    expect(packer).toContain('const archiveFiles = [...packagedFiles.map(({ archiveName }) => archiveName), "manifest.json", readmeFileName]');
    expect(packer).toContain('["-a", "-c", "-f", outputFile, ...archiveFiles]');
    expect(packer).not.toContain('["-a", "-c", "-f", outputFile, "."]');
  });
});
